/// Emoji whose shortcode contains [query]: an exact match, then the ones
/// starting with it, then the rest.
List<(String, String)> matchEmoji(String query, {int max = 24}) {
  final q = query.toLowerCase();
  final starts = [
    for (final e in emojiShortcodes)
      if (e.$1 == q) e,
    for (final e in emojiShortcodes)
      if (e.$1 != q && e.$1.startsWith(q)) e,
  ];
  final rest = [
    for (final e in emojiShortcodes)
      if (!e.$1.startsWith(q) && e.$1.contains(q)) e,
  ];
  return [...starts, ...rest].take(max).toList();
}

/// A row of matching emoji above the text box.
class EmojiSuggestions extends StatelessWidget {
  const EmojiSuggestions({
    super.key,
    required this.query,
    required this.onPick,
  });
  final String query;
  final ValueChanged<String> onPick;

  @override
  Widget build(BuildContext context) {
    final found = matchEmoji(query);
    if (found.isEmpty) return const SizedBox.shrink();
    return SizedBox(
      height: 60,
      child: ListView(
        scrollDirection: Axis.horizontal,
        padding: const EdgeInsets.fromLTRB(10, 6, 10, 0),
        children: [
          for (final (name, emoji) in found)
            Tooltip(
              message: ':$name:',
              child: InkWell(
                borderRadius: BorderRadius.circular(8),
                onTap: () => onPick(emoji),
                child: Padding(
                  padding: const EdgeInsets.symmetric(horizontal: 6),
                  child: Column(
                    mainAxisSize: MainAxisSize.min,
                    children: [
                      Text(emoji, style: const TextStyle(fontSize: 24)),
                      Text(
                        name,
                        style: Theme.of(context).textTheme.labelSmall,
                        maxLines: 1,
                      ),
                    ],
                  ),
                ),
              ),
            ),
        ],
      ),
    );
  }
}
